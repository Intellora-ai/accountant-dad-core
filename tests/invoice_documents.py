"""Six documents, in the shape a reader returns them, and one warning.

READ THIS BEFORE QUOTING ANY NUMBER THAT CAME OUT OF THIS FILE
================================================================

    THESE FIXTURES PROVE PARSER AND VALIDATION BEHAVIOUR.
    THEY PROVE NOTHING WHATSOEVER ABOUT PRODUCTION OCR ACCURACY.

Every character below was TYPED BY HAND into the shape a reading engine
produces. Not one of them was read off a photograph, and no photograph of any
of them exists. They answer questions of the form "given exactly these
characters, does the parser find the IGST figure and refuse the CGST/SGST
contradiction". They cannot answer "does tesseract produce these characters
from a real bill", because nobody has ever handed this repository a real
Indian GST invoice to try.

A SYNTHETIC RENDER IS NOT A PHOTOGRAPH, and this repository has already paid
for forgetting that once. `artifacts/ground_truth` scored 20/20 on a tier that
was inventing every total, because the corpus was generated by the same code
being measured - a corpus measuring its own generator.
`docs/EXTRACTION_MEASURED.md` carries the correction. This file carries the
warning so it travels with the data rather than living in a document nobody
opens.

WHY TEXT AND WORD LISTS RATHER THAN IMAGES
--------------------------------------------
Pillow can draw text onto a canvas and tesseract can read it back, and the
result would look like a measurement. It would be a measurement of Pillow's
font rendering. The honest version of "captured reading output" is the text and
the per-word scores, which is what a real capture would give us - so that is
what these are, and the day real redacted captures arrive they drop into
exactly this shape. `docs/INVOICE_EXTRACTION_FRAMEWORK.md` holds the contract.

NO REAL PARTY, NO REAL REGISTRATION NUMBER
--------------------------------------------
Every name is invented. Every GSTIN below is shaped like a GSTIN - it has to
be, or it would test nothing - and none belongs to a real registered person:
the PAN blocks spell things no registrar issues.

WHAT EACH ONE IS FOR
---------------------
    INTRA_STATE       a complete CGST/SGST bill that adds up. The happy path.
    INTER_STATE       IGST, a place of supply, several lines.
    WITH_DISCOUNT     a discount, a round-off, an amount in words, an IRN and
                      an e-way bill.
    NOT_AN_INVOICE    a museum catalogue page. Reads perfectly; is not a bill.
    BARELY_READABLE   what a bad photograph comes back as.
    MISSING_FIELDS    a real bill with no number and no date on it.
"""

from __future__ import annotations

from dataclasses import dataclass

from accountant.invoice.parse import Reading, Word

#: What the text-layer tier is entitled to state about its own certainty.
#: `cage/confidence.EXACT` is 1.0 and means "there is no pixel and no estimate";
#: these fixtures are characters, so that is the honest score for them.
TEXT_LAYER: str = "pdf_text_layer"

#: The name a reading rebuilt from word scores carries in these fixtures.
PHOTOGRAPH: str = "free_ocr"


@dataclass(frozen=True)
class Fixture:
    """One hand-written document and what a person reading it would say.

    `expected` is deliberately sparse. It holds the facts a test asserts
    EXACTLY - a paise figure, a GSTIN, a status - and not a full transcription,
    because an expectation nobody checked by hand is not a ground truth, it is
    the parser's own output written down twice.
    """

    name: str
    text: str
    expected: dict[str, object]


