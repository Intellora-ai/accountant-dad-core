def text_reading(fixture: Fixture, *, confidence: float = 1.0) -> Reading:
    """The fixture as a text-layer reading - characters, one stated score."""
    return Reading.from_text(fixture.text, source=TEXT_LAYER, confidence=confidence)


def word_reading(fixture: Fixture, *, confidence: int) -> Reading:
    """The fixture as a reading rebuilt from word scores, all at `confidence`.

    ONE SCORE FOR EVERY WORD, which no real engine ever produces. It is what
    lets a test assert an EXACT field confidence: `min(word)/100` over a set of
    identical numbers is that number, so a test can pin `0.62` rather than
    asserting something vague about a range.

    THE COLUMN GAPS ARE LOST, and that is not a defect of this helper - it is
    what happens to any line rebuilt from a word list, including the real one in
    `extract/pagereader.py`. A test that used this and expected the text-layer
    answer would be testing a tier that does not exist.
    """
    return Reading.from_words(
        [
            [Word(text=word, confidence=confidence) for word in line.split()]
            for line in fixture.text.splitlines()
        ],
        source=PHOTOGRAPH,
    )
