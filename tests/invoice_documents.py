# =============================================================================
# 4. not an invoice at all
# =============================================================================
#
# Deliberately a document that READS PERFECTLY. The point of this fixture is
# that a clean reading and a bill are different things - the failure this whole
# package exists to separate. Nothing a bill prints is on it: no invoice, no
# tax, no amount, no registration number, no rupee figure.
#
# THE WORDING HAD TO BE CHOSEN CAREFULLY, AND THAT IS A FINDING RATHER THAN AN
# INCONVENIENCE. The first draft of this fixture read "Book of hours" and
# "wooden boards", and `invoicelike.looks_like_a_bill` reported that it PRINTS A
# CURRENCY - because that signal's pattern is `₹|Rs\\.?|INR` with no word
# boundary, so the `rs` inside `hours` matches. One signal is not two, so the
# verdict was still "not a bill", but the SIGNAL LIST shown to a person named a
# currency that is not on the page.
#
# `invoicelike.py` is not this package's to edit. The finding is recorded here
# and in `docs/INVOICE_EXTRACTION_FRAMEWORK.md`, and this fixture is worded to
# fire NOTHING, so it tests `UNKNOWN_DOCUMENT` rather than a false signal.

