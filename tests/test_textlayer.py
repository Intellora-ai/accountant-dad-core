"""The text-layer reader: the rung of the ladder that needs no pixels.

WHY THIS FILE EXISTS
--------------------
A GST e-invoice, an emailed bill and a supplier PDF all carry a TEXT LAYER -
the characters the producing program wrote, still present in the file. For
those, OCR is the wrong tool. Extraction is EXACT: the bytes say `584.10` and
there is nothing to be unsure about. OCR is for photographs and scans, which
are a different rung and a different tier.

Noticing that these are a LADDER rather than two competing readers is the whole
saving, and this file is where the top rung is held to its promise:

    it was READ, not guessed        every field it answers carries
                                    `confidence.EXACT`, which is exactly 1.0
    it never guesses instead        a PDF with no text layer says so and stops.
                                    It does not fall through to a lower rung
                                    and it does not invent a number
    it never raises                 a corrupt PDF is a refusal with a sentence,
                                    never a traceback out of `pypdf`

WHY SO MANY OF THESE TESTS ARE REFUSALS
----------------------------------------
A reader is easy to make look good: read the clean cases and stay quiet about
the rest. The dangerous output is not a blank, it is a CONFIDENT WRONG NUMBER -
a total lifted off a "PREVIOUS BALANCE" line, a `06/10/2026` read as the 6th of
October when the supplier wrote the 10th of June. Both post to a real ledger at
confidence 1.0 with nothing on screen to notice. So the tests that matter here
are the ones that prove a wrong answer is refused rather than returned, and the
corpus section below measures exactly that: how many fields are RIGHT, and how
many are WRONG rather than unread.

WHAT THIS FILE DOES NOT PROVE
------------------------------
That the reader is accurate on real customer bills. The twenty PDFs measured
below are `SYNTHETIC_EVIDENCE` generated by `scripts/build_ground_truth.py`;
they are an engineering benchmark and real-bill accuracy stays `NOT_MEASURED`
(`H-02`). A number measured here must never be reported as customer accuracy.

That a field it read is CORRECT. Exactness is about the reading, not about the
document: a supplier who prints the wrong total gets it read perfectly. That is
what the conservation laws are for, and they run afterwards.

That every PDF in the world parses. `pypdf` is one parser with its own bugs.
What is proved is that its failures come back as refusals.

NO NETWORK. The PDFs are either generated in this file or read off disk.
"""

