RULE = "------------------------------------------------------------"
DATE_LINE = "DATE: 2026-04-01"
TAX_LINE = "GST                                                  188.32"
TOTAL_LINE = "TOTAL                                              1,234.56"
ITEM_LINE = "PACKAGING MATERIAL                                    46.24"


def bill_with(*replacements: tuple[str, str]) -> TextLayerReading:
    """`BILL`, with whole lines swapped, read back through the reader."""
    lines: list[str] = list(BILL)
    for old, new in replacements:
        lines[lines.index(old)] = new
    return read(pdf_bytes(lines))


# ---- it was read, not guessed ------------------------------------------------


def test_a_bill_with_a_text_layer_is_reported_as_read() -> None:
    assert read(pdf_bytes(BILL)).outcome is Outcome.READ


def test_the_date_printed_on_the_bill_is_the_date_returned() -> None:
    assert read(pdf_bytes(BILL)).observation.date.value == datetime.date(2026, 4, 1)


def test_the_supplier_printed_on_the_bill_is_the_party_returned() -> None:
    assert read(pdf_bytes(BILL)).observation.party.value == "SHARMA TRADERS"


def test_a_grouped_rupee_total_becomes_integer_paise() -> None:
    """`1,234.56` is 123456 paise. Not 1234.56 rupees, and never a float."""
    assert read(pdf_bytes(BILL)).observation.total_paise.value == 123_456


def test_the_tax_line_is_read_separately_from_the_total() -> None:
    assert read(pdf_bytes(BILL)).observation.tax_paise.value == 18_832


def test_the_line_items_are_read_as_integer_paise_in_printed_order() -> None:
    assert read(pdf_bytes(BILL)).observation.line_paise == (100_000, 4_624)


def test_every_field_read_off_a_text_layer_carries_confidence_exactly_one() -> None:
    """EXACT, not "very high". There is no pixel here and no estimate: the file
    says `1,234.56` in characters somebody's software wrote. A score of 0.99
    would be a claim about uncertainty that does not exist."""
    fields = read(pdf_bytes(BILL)).fields
    assert [f.confidence for f in fields.values()] == [EXACT] * len(FIELDS)
    assert EXACT == 1.0
    # The list above is only as good as the names in it. Pinning the module's
    # own tuple is what stops a field being dropped from `fields` and the
    # length check quietly agreeing with the shorter list.
    assert MODULE_FIELDS == FIELDS
    assert set(fields) == set(FIELDS)


def test_the_control_a_field_this_bill_does_not_carry_scores_zero_not_one() -> None:
    """THE CONTROL on the test above. A reader that stamped `EXACT` on the
    record rather than on each field it actually read would pass that test and
    fail this one, and would then hand the decision layer a 1.0 for a field
    nobody read."""
    reading = bill_with(("DATE: 2026-04-01", "INVOICE DATED SOMETIME LAST YEAR"))
    assert reading.observation.date.value is None
    assert reading.observation.date.confidence == 0.0


def test_an_unread_field_still_says_where_it_came_from() -> None:
    reading = bill_with(("DATE: 2026-04-01", "NO DATE PRINTED HERE"))
    assert reading.observation.date.source.startswith(NOT_FOUND)


def test_every_amount_returned_is_an_int_and_never_a_float_or_a_bool() -> None:
    """Money is integer paise everywhere in this repository. `bool` is refused
    with the ints because `isinstance(True, int)` is True in Python, so a flag
    that reached an amount would balance a one-paisa entry."""
    observation = read(pdf_bytes(BILL)).observation
    amounts = [observation.total_paise.value, observation.tax_paise.value]
    amounts += list(observation.line_paise or ())
    assert all(type(a) is int for a in amounts)


