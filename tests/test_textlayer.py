def bill_with(*replacements: tuple[str, str]) -> TextLayerReading:
    """`BILL`, with whole lines swapped, read back through the reader."""
    lines: list[str] = list(BILL)
    for old, new in replacements:
        lines[lines.index(old)] = new
    return read(pdf_bytes(lines))


