def test_an_embedded_file_reference_is_not_followed(tmp_path: Path) -> None:
    """A PDF may name another file and ask that it be opened. Following that is
    how a document reader becomes a file-disclosure bug.

    The named file is REAL and carries a marker this test wrote, so the check
    is falsifiable: a reader that followed the reference would put the marker
    in the text it returns, and this assertion would fail. Pointing at a path
    that does not exist would pass no matter what the reader did."""
    secret = tmp_path / "secret.txt"
    _ = secret.write_text("MARKER-8f31-DO-NOT-READ-ME", encoding="utf-8")
    poisoned = pdf_bytes(BILL).replace(
        b"/Type /Catalog",
        b"/Type /Catalog /OpenAction << /S /Launch /F ("
        + str(secret).encode("ascii")
        + b") >>",
    )
    reading = read(poisoned)
    assert "MARKER-8f31" not in reading.text
    assert reading.observation.total_paise.value == 123_456


