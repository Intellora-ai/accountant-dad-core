# ---- the corpus: twenty real PDFs, measured -----------------------------------


def corpus_cases() -> list[dict[str, Any]]:
    """Every PDF case in `artifacts/ground_truth/`, newest build on disk."""
    loaded: list[dict[str, Any]] = []
    for path in sorted(CASES.glob("*.json")):
        case: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        if str(case["input_type"]) == "PDF":
            loaded.append(case)
    return loaded


def expected_answer(case: dict[str, Any]) -> dict[str, object]:
    """The truth the document was RENDERED FROM, converted here.

    Converted with `Decimal` in this file rather than through the reader's own
    `paise_or_none`. A comparison that used the reader to build both sides
    would agree with itself no matter how wrong it was.
    """
    expected: dict[str, Any] = case["expected"]
    items: list[dict[str, Any]] = expected["line_items"]
    return {
        "date": datetime.date.fromisoformat(str(expected["date"])),
        "party": str(expected["party"]),
        "total_paise": int(Decimal(str(expected["total_amount"])) * 100),
        "tax_paise": int(Decimal(str(expected["tax_amount"])) * 100),
        "line_paise": tuple(int(Decimal(str(i["amount"])) * 100) for i in items),
    }


def read_answer(observation: Observation) -> dict[str, object]:
    return {
        "date": observation.date.value,
        "party": observation.party.value,
        "total_paise": observation.total_paise.value,
        "tax_paise": observation.tax_paise.value,
        "line_paise": observation.line_paise,
    }


def score_corpus() -> tuple[dict[str, int], dict[str, int]]:
    """Per field: how many were EXACTLY right, and how many were WRONG.

    Wrong is the number that matters. A field left unread costs a question; a
    field read wrongly at confidence 1.0 posts a number nobody checked.
    """
    right: dict[str, int] = dict.fromkeys(FIELDS, 0)
    wrong: dict[str, int] = dict.fromkeys(FIELDS, 0)
    for case in corpus_cases():
        data = (DOCUMENTS / str(case["document"])).read_bytes()
        got = read_answer(read(data).observation)
        want = expected_answer(case)
        for name in FIELDS:
            if got[name] == want[name]:
                right[name] += 1
            elif got[name] is not None:
                wrong[name] += 1
    return right, wrong


def test_every_pdf_in_the_corpus_is_reported_as_carrying_a_text_layer() -> None:
    outcomes = {
        str(case["case_id"]): read((DOCUMENTS / str(case["document"])).read_bytes())
        for case in corpus_cases()
    }
    assert len(outcomes) == 20
    assert all(r.outcome is Outcome.READ for r in outcomes.values()), outcomes


def test_no_field_read_from_the_twenty_corpus_pdfs_is_wrong() -> None:
    """The claim that matters, and the one this tier is built to make. A field
    is either exactly the value the document was generated from, or it is
    unread. There is no third case, because the third case is a wrong number
    carrying confidence 1.0."""
    _, wrong = score_corpus()
    assert sum(wrong.values()) == 0, wrong


