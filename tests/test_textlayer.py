# ---- a PDF, built here, so the bytes under test are real ---------------------


def pdf_bytes(lines: Sequence[str], *, pages: int = 1) -> bytes:
    """A real PDF 1.4 carrying `lines` as a Helvetica text layer.

    Hand-built rather than taken from a library, for the reason
    `scripts/build_ground_truth.py` gives about the corpus: the xref offsets are
    MEASURED off the bytes as they are emitted, which is the only way a
    cross-reference table is correct. A fixture file would also work, but then
    the test could not vary one line of a bill to make a point.
    """
    per_page = max(1, -(-len(lines) // pages))
    chunks = [lines[i : i + per_page] for i in range(0, len(lines), per_page)] or [[]]
    page_ids = [3 + i for i in range(len(chunks))]
    content_ids = [3 + len(chunks) + i for i in range(len(chunks))]
    font_id = 3 + 2 * len(chunks)

    kids = " ".join(f"{i} 0 R" for i in page_ids)
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        f"<< /Type /Pages /Kids [{kids}] /Count {len(chunks)} >>".encode("ascii"),
    ]
    objects += [
        (
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources "
            f"<< /Font << /F1 {font_id} 0 R >> >> /Contents {cid} 0 R >>"
        ).encode("ascii")
        for cid in content_ids
    ]
    objects += [_content_stream(chunk) for chunk in chunks]
    objects.append(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica "
        b"/Encoding /WinAnsiEncoding >>"
    )
    return _assemble(objects)


def _content_stream(lines: Sequence[str]) -> bytes:
    drawn = "".join(f"({_pdf_escape(line)}) Tj T*\n" for line in lines)
    stream = f"BT /F1 9 Tf 40 800 Td 12 TL\n{drawn}ET\n".encode("ascii")
    length = str(len(stream)).encode("ascii")
    return b"<< /Length " + length + b" >>\nstream\n" + stream + b"endstream"


def _pdf_escape(text: str) -> str:
    out = text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
    return "".join(c if ord(c) < 128 else "?" for c in out)


def _assemble(objects: Sequence[bytes]) -> bytes:
    out = bytearray(b"%PDF-1.4\n")
    offsets: list[int] = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode("ascii") + body + b"\nendobj\n"
    xref_at = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode("ascii") + b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("ascii")
    out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n".encode("ascii")
    out += f"startxref\n{xref_at}\n%%EOF\n".encode("ascii")
    return bytes(out)


